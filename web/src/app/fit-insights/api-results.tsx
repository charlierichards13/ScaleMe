"use client";

import { useRef, useState } from "react";
import type { FitResult } from "@/lib/fit/client";

export const statusLabels = {
  supported: "Supported",
  unclear: "Unclear",
  not_evidenced: "Not evidenced",
} as const;
type Status = keyof typeof statusLabels;

// v0.1 returns IDs, not extracted descriptions or importance. Never infer them.
export function ApiResults({ result }: { result: FitResult }) {
  const [filter, setFilter] = useState<Status | "all">("all");
  const filterSelect = useRef<HTMLSelectElement>(null);
  const { analysis } = result;
  const visible = analysis.assessments.filter(
    (a) => filter === "all" || a.status === filter,
  );
  return (
    <div className="fit-app-results">
      <div className="fit-app-notice">
        <strong>Fictional API demonstration</strong>
        <p>
          This fixed sample is synthetic. It is not based on your drafts and was
          not generated by live AI.
        </p>
      </div>
      <p className="fit-app-summary">{analysis.summary}</p>
      <dl className="fit-app-counts" aria-label="Sample assessment counts">
        {(Object.keys(statusLabels) as Status[]).map((status) => (
          <div key={status} className={`fit-app-${status}`}>
            <dt>{statusLabels[status]}</dt>
            <dd>
              {analysis.assessments.filter((a) => a.status === status).length}
            </dd>
          </div>
        ))}
      </dl>
      <p className="fit-app-help">
        Counts describe returned sample assessments, not hiring probability.
        “Not evidenced” means not shown in the resume, not a lack of ability.
      </p>
      <div className="fit-app-section-heading">
        <h3>Requirement evidence</h3>
        <label>
          Show{" "}
          <select
            ref={filterSelect}
            value={filter}
            onChange={(e) => setFilter(e.target.value as Status | "all")}
          >
            <option value="all">All statuses</option>
            {(Object.keys(statusLabels) as Status[]).map((s) => (
              <option key={s} value={s}>
                {statusLabels[s]}
              </option>
            ))}
          </select>
        </label>
      </div>
      <p className="fit-app-help">
        The API returns requirement IDs; descriptions and importance are not
        included. Job quotes describe the role and do not prove candidate
        experience.
      </p>
      <div className="fit-app-assessments">
        {visible.map((a) => (
          <article key={a.requirementId} className="fit-app-assessment">
            <div className="fit-app-section-heading">
              <h4>Requirement {a.requirementId}</h4>
              <span className={`fit-app-badge fit-app-${a.status}`}>
                {statusLabels[a.status]}
              </span>
            </div>
            <p>{a.explanation}</p>
            {a.evidence.length ? (
              a.evidence.map((e, i) => (
                <figure key={i} className="fit-app-quote">
                  <figcaption>
                    {e.source === "job"
                      ? "Job · Requirement context only"
                      : "Fictional resume · Candidate-reported"}
                    {e.section ? ` · ${e.section}` : ""}
                  </figcaption>
                  <blockquote>“{e.quote}”</blockquote>
                </figure>
              ))
            ) : (
              <p className="fit-app-missing">
                No evidence quote returned for this requirement.
              </p>
            )}
          </article>
        ))}
        {!visible.length && (
          <div className="fit-app-empty">
            <h4>No sample requirements in this view</h4>
            <p>Try another status to see the returned evidence.</p>
            <button
              type="button"
              className="fit-app-secondary"
              onClick={() => {
                setFilter("all");
                filterSelect.current?.focus();
              }}
            >
              Show all requirements
            </button>
          </div>
        )}
      </div>
      <div className="fit-app-next-grid">
        <ResultList
          title="Strengths in the sample"
          items={analysis.strengths}
          empty="No strengths returned."
        />
        <ResultList
          title="Clarification questions"
          items={analysis.clarificationQuestions}
          empty="No clarification questions returned."
        />
        <ResultList
          title="Possible next steps"
          items={analysis.growthSuggestions}
          empty="No next steps returned."
        />
      </div>
      <p className="fit-app-help">
        Questions are returned for the whole analysis; the v0.1 API does not
        link them to specific requirements. Candidate-reported evidence is not
        independently verified.
      </p>
      <p className="fit-app-disclaimer">{analysis.disclaimer}</p>
    </div>
  );
}

function ResultList({
  title,
  items,
  empty,
}: {
  title: string;
  items: string[];
  empty: string;
}) {
  return (
    <section>
      <h3>{title}</h3>
      {items.length ? (
        <ul>
          {items.map((item, i) => (
            <li key={i}>{item}</li>
          ))}
        </ul>
      ) : (
        <p>{empty}</p>
      )}
    </section>
  );
}
