import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { demoAnalysis } from "@/lib/ai/demo";
import type { FitAnalysis } from "@/lib/fit/client";
import { ApiResults } from "./api-results";

const render = (analysis: FitAnalysis = demoAnalysis) =>
  renderToStaticMarkup(
    createElement(ApiResults, { result: { mode: "demo", analysis } }),
  );

describe("API results presentation", () => {
  it("labels fixed synthetic provenance and never claims draft analysis or required coverage", () => {
    const html = render();
    expect(html).toContain("not based on your drafts");
    expect(html).toContain("not generated by live AI");
    expect(html).toContain("Requirement r1");
    expect(html).toContain("descriptions and importance are not included");
    expect(html).not.toContain("required requirements supported");
  });
  it("shows supported, unclear, not-evidenced explanations and distinguishes job context", () => {
    const html = render({
      ...demoAnalysis,
      assessments: [
        ...demoAnalysis.assessments,
        {
          requirementId: "r3",
          status: "unclear",
          explanation: "Fictional context is incomplete.",
          evidence: [
            { source: "job", quote: "Fictional role requires feedback." },
          ],
        },
      ],
    });
    for (const text of [
      "Supported",
      "Unclear",
      "Not evidenced",
      "No evidence quote returned",
      "Fictional context is incomplete.",
      "Job · Requirement context only",
      "Built an internal employee portal.",
      "Candidate-reported",
      "not independently verified",
      "How did you test the portal before release?",
    ])
      expect(html).toContain(text);
  });
  it("renders hostile response strings as text across all prose fields", () => {
    const payload = '<img src=x onerror="alert(1)">';
    const html = render({
      ...demoAnalysis,
      summary: payload,
      strengths: [payload],
      clarificationQuestions: [payload],
      growthSuggestions: [payload],
      disclaimer: payload,
      assessments: [
        {
          requirementId: payload,
          status: "unclear",
          explanation: payload,
          evidence: [{ source: "resume", quote: payload, section: payload }],
        },
      ],
    });
    expect(html).not.toContain("<img");
    expect(html.match(/&lt;img/g)?.length).toBe(9);
  });
  it("keeps empty follow-up sections honest", () => {
    const html = render({
      ...demoAnalysis,
      strengths: [],
      clarificationQuestions: [],
      growthSuggestions: [],
    });
    expect(html).toContain("No strengths returned.");
    expect(html).toContain("No clarification questions returned.");
    expect(html).toContain("No next steps returned.");
  });
});
